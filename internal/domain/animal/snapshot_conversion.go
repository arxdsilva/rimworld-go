package animal

// SnapshotFromState is the temporary migration boundary from the existing
// live state to nine independently owned groups.
func SnapshotFromState(a State) Snapshot {
	return Snapshot{
		Identity: Identity{
			Species: a.Species,
			Tame:    a.Tame,
			Name:    a.Name,
			Female:  a.Female,
			HasSex:  a.HasSex,
			Born:    a.Born,
			Herd:    a.Herd,
		},
		Vitals: Vitals{
			Injury:     a.Injury,
			Hunger:     a.Hunger,
			Food:       a.Food,
			Rest:       a.Rest,
			Starving:   a.Starving,
			Downed:     a.Downed,
			DownedTick: a.DownedTick,
		},
		Intent: Intent{
			Mode:       a.Mode,
			Target:     a.Target,
			NextThink:  a.NextThink,
			Cooldown:   a.Cooldown,
			NextDecide: a.NextDecide,
			Leaving:    a.Leaving,
			ExitX:      a.ExitX,
			ExitY:      a.ExitY,
			Errand:     a.Errand,
			Dormant:    a.Dormant,
		},
		Motion: Motion{
			Path:     a.Path,
			PathI:    a.PathI,
			GoalX:    a.GoalX,
			GoalY:    a.GoalY,
			RetryAt:  a.RetryAt,
			StepGait: a.StepGait,
		},
		Threat: Threat{
			Attacker:          a.Attacker,
			FleeUntil:         a.FleeUntil,
			Manhunter:         a.Manhunter,
			HuntSince:         a.HuntSince,
			ChargeSince:       a.ChargeSince,
			NextCharge:        a.NextCharge,
			ChaseWarnedAt:     a.ChaseWarnedAt,
			ChaseWarnedTarget: a.ChaseWarnedTarget,
		},
		Feeding: Feeding{
			Feed:      a.Feed,
			FeedLeft:  a.FeedLeft,
			NextFeed:  a.NextFeed,
			FeedClaim: a.FeedClaim,
		},
		Handling: Handling{
			Designated:    a.Designated,
			TameMark:      a.TameMark,
			TameRetry:     a.TameRetry,
			NoFollow:      a.NoFollow,
			Master:        a.Master,
			Bond:          a.Bond,
			Trained:       a.Trained,
			TrainDecay:    a.TrainDecay,
			NextBondCheck: a.NextBondCheck,
			ConfusedUntil: a.ConfusedUntil,
		},
		Reproduction: Reproduction{
			Pregnant:  a.Pregnant,
			Mated:     a.Mated,
			Product:   a.Product,
			Mate:      a.Mate,
			MateLeft:  a.MateLeft,
			MateUntil: a.MateUntil,
			Mother:    a.Mother,
		},
		Medical: Medical{
			Body: a.Body,
		},
	}
}

