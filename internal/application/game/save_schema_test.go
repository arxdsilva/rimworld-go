// The save format's safety net (MASTER_SPEC §45). Gob matches struct fields
// by name, so renaming or removing a saved field silently drops its data,
// and changing a field's kind makes Load fail. TestSaveSchema lists every
// field gob writes, and TestSaveV12Fixture keeps a save of the v12 format
// loading for good.

const (
	saveSchemaGolden = "testdata/save_schema.txt"
	saveSchemaEnv    = "RIMWORLD_UPDATE_SAVE_SCHEMA"
	saveV12Fixture   = "testdata/v12.sav"
	saveV12Env       = "RIMWORLD_UPDATE_SAVE_V12"
)

// saveSchemaHeader opens the list; TestSaveSchema skips lines starting '#'.
const saveSchemaHeader = `# Every field a save writes, as gob sees it. Generated by TestSaveSchema.
# Read a line as: path type [= underlying]. "[]" is a slice or array element,
# "{key}" and "{}" a map's key and element. Pointers are left out, as gob
# flattens them. Refresh: RIMWORLD_UPDATE_SAVE_SCHEMA=1 go test -race -run SaveSchema ./internal/application/game/
`

// schemaRoots is what Save encodes.
func schemaRoots() map[string]reflect.Type {
	return map[string]reflect.Type{
		"SaveInfo":  reflect.TypeFor[SaveInfo](),
		"saveState": reflect.TypeFor[saveState](),
	}
}

// saveSchema is the sorted list of what gob writes for the roots.
func saveSchema() []string {
	w := schemaWalk{onPath: map[reflect.Type]bool{}}
	for name, t := range schemaRoots() {
		w.visit(name, t)
	}
	slices.Sort(w.lines)
	return w.lines
}

// schemaWalk walks types the way encoding/gob does. onPath is the cycle
// guard: a type is expanded again on each path, except inside itself
// (saveState.ExtraMaps[].State is a saveState).
type schemaWalk struct {
	lines  []string
	onPath map[reflect.Type]bool
}

func (w *schemaWalk) visit(path string, t reflect.Type) {
	t = schemaDeref(t)
	line := path + " " + schemaName(t)
	if t.PkgPath() != "" && t.Kind() != reflect.Struct {
		line += " = " + schemaUnderlying(t)
	}
	if enc := schemaEncoder(t); enc != "" { // gob calls it instead of reading fields
		w.lines = append(w.lines, line+" (leaf: "+enc+")")
		return
	}
	switch t.Kind() {
	case reflect.Struct:
		if w.onPath[t] {
			w.lines = append(w.lines, line+" (cycle)")
			return
		}
		w.lines = append(w.lines, line)
		w.onPath[t] = true
		for i := range t.NumField() {
			if f := t.Field(i); schemaSent(f) {
				w.visit(path+"."+f.Name, f.Type)
			}
		}
		delete(w.onPath, t)
	case reflect.Slice, reflect.Array:
		w.lines = append(w.lines, line)
		w.visit(path+"[]", t.Elem())
	case reflect.Map:
		w.lines = append(w.lines, line)
		w.visit(path+"{key}", t.Key())
		w.visit(path+"{}", t.Elem())
	default:
		w.lines = append(w.lines, line) // a basic kind, or an interface gob cannot look into
	}
}

// schemaSent is encoding/gob's isSent: exported, and not a chan or func.
func schemaSent(f reflect.StructField) bool {
	if !f.IsExported() {
		return false
	}
	k := schemaDeref(f.Type).Kind()
	return k != reflect.Chan && k != reflect.Func
}

func schemaDeref(t reflect.Type) reflect.Type {
	for t.Kind() == reflect.Pointer {
		t = t.Elem()
	}
	return t
}

// schemaEncoder names the interface gob would use instead of t's fields:
// GobEncoder, then BinaryMarshaler, on t or on *t (gob's validUserType).
func schemaEncoder(t reflect.Type) string {
	for _, e := range []struct {
		name  string
		iface reflect.Type
	}{
		{"gob.GobEncoder", reflect.TypeFor[gob.GobEncoder]()},
		{"encoding.BinaryMarshaler", reflect.TypeFor[encoding.BinaryMarshaler]()},
	} {
		if t.Implements(e.iface) || reflect.PointerTo(t).Implements(e.iface) {
			return e.name
		}
	}
	return ""
}

// schemaName is a deterministic name for t, with package paths (which
// reflect's String leaves out). A generic type's Name already has its
// arguments' paths.
func schemaName(t reflect.Type) string {
	t = schemaDeref(t)
	if t.Name() != "" {
		if t.PkgPath() == "" {
			return t.Name()
		}
		return t.PkgPath() + "." + t.Name()
	}
	return schemaUnderlying(t)
}

// schemaUnderlying spells t's shape: this is what a named type's name hides,
// and an array's length or a kind are what gob refuses a change of.
func schemaUnderlying(t reflect.Type) string {
	switch t.Kind() {
	case reflect.Slice:
		return "[]" + schemaName(t.Elem())
	case reflect.Array:
		return fmt.Sprintf("[%d]%s", t.Len(), schemaName(t.Elem()))
	case reflect.Map:
		return "map[" + schemaName(t.Key()) + "]" + schemaName(t.Elem())
	default:
		return t.Kind().String()
	}
}

// readSaveSchema reads the golden list without its comments.
func readSaveSchema(t *testing.T) []string {
	t.Helper()
	data, err := os.ReadFile(saveSchemaGolden)
	if err != nil {
		t.Fatalf("%v (create the list: %s=1 go test -race -run SaveSchema ./internal/application/game/)", err, saveSchemaEnv)
	}
	var lines []string
	for line := range strings.Lines(string(data)) {
		if line = strings.TrimRight(line, "\n"); line != "" && !strings.HasPrefix(line, "#") {
			lines = append(lines, line)
		}
	}
	return lines
}

// schemaMinus is the lines of a that b lacks.
func schemaMinus(a, b []string) []string {
	var out []string
	for _, line := range a {
		if !slices.Contains(b, line) {
			out = append(out, line)
		}
	}
	return out
}

// TestSaveSchema fails on any change to what a save holds. A line gone or
// changed means data an older save holds no longer has a home; a line only
// added is safe in gob, and is listed so the list stays complete.
func TestSaveSchema(t *testing.T) {
	got := saveSchema()
	if os.Getenv(saveSchemaEnv) != "" {
		text := saveSchemaHeader + strings.Join(got, "\n") + "\n"
		if err := os.WriteFile(saveSchemaGolden, []byte(text), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	t.Parallel()
	want := readSaveSchema(t)
	removed, added := schemaMinus(want, got), schemaMinus(got, want)
	if len(removed) > 0 {
		t.Errorf(`save schema: %d saved field line(s) removed or changed. Gob matches fields by name and kind, so it would silently drop this data from existing saves, or reject them on load.
Bump SaveVersion, add a migrateSave step that carries the old field over (keep the old field, read-only, for it to read), then refresh the list with %s=1.
Only if the sole difference is a type's name or package, with the same field names and kinds, is the data safe: then refresh the list without a bump, and say so in the commit.
Gone or changed:
  %s
New lines (a changed field's new form appears here):
  %s`, len(removed), saveSchemaEnv, strings.Join(removed, "\n  "), strings.Join(added, "\n  "))
		return
	}
	if len(added) > 0 {
		t.Errorf(`save schema: %d new saved field line(s), not on the list. A new field is safe in gob (older saves leave it zero), so no SaveVersion bump is needed for that alone.
Refresh the list to keep it complete: %s=1 go test -race -run SaveSchema ./internal/application/game/
New:
  %s`, len(added), saveSchemaEnv, strings.Join(added, "\n  "))
	}
}

// saveV12Hash is the state hash of the v12 fixture as Load restores it.
//
// When a later version bumps SaveVersion, this fixture stays exactly as it
// is: old versions must keep loading. Do not regenerate it, and do not move
// this pin to get a test to pass. Only a migration step that really changes a
// v12 save's state may move the hash: re-pin it then, saying in the commit
// why that migration changes it.
const saveV12Hash = uint64(0x9f9a65eaaf7f6e3a)

// v12Colony is the colony in the fixture: rich in state, so that as many
// saved fields as practical are non-zero.
func v12Colony(t *testing.T) *Game {
	t.Helper()
	g := buildSetup(t, setupFor(t, "broken_hull", func(s *Setup) { s.MapSize = 60 }))
	stepUntilLanded(t, g)
	const cx, cy = 30, 30
	for _, c := range []command.Command{
		{Kind: command.DesignateStockpile, X: cx + 1, Y: cy + 3, X2: cx + 4, Y2: cy + 5},
		{Kind: command.DesignateHarvest, X: 0, Y: 0, X2: 59, Y2: 59},
		{Kind: command.DesignateHunt, X: 0, Y: 0, X2: 59, Y2: 59},
		{Kind: command.DesignateGrowZone, X: cx - 6, Y: cy - 6, X2: cx - 3, Y2: cy - 4, Build: mustCrop(t, "radish")},
		{Kind: command.DesignatePlan, X: 2, Y: 2, X2: 4, Y2: 4, Enabled: true},
		{Kind: command.DesignateSnowClear, X: 8, Y: 5, X2: 10, Y2: 6, Enabled: true},
		{Kind: command.SetDefaultCare, Index: int(medcare.Animals), Mode: uint8(medcare.NoCare)},
		{Kind: command.SetHomeAuto, Enabled: false},
	} {
		g.Enqueue(c)
	}
	for i, k := range []construction.Kind{construction.Campfire, construction.Bed, construction.SolarPanel, construction.Battery,
		construction.SentryTurret, construction.Heater, construction.ResearchBench, construction.Stove} {
		x, y := 18+3*i, 24
		g.placeFrameStuff(k, item.Steel, construction.South, x, y)
		if fid := g.layerFrameAt(x, y, construction.DefOf(k).Layer); fid != 0 {
			fr, _ := g.frames.Get(fid)
			g.completeFrame(fid, fr)
		}
	}
	for x := 20; x < 26; x++ {
		g.Enqueue(command.Command{Kind: command.DesignateBuild, X: x, Y: 36, X2: x, Y2: 36, Build: uint8(construction.Wall)})
	}
	g.SpawnStack(item.Parka, 1, cx+5, cy)
	g.SpawnStack(item.Wood, 40, cx+6, cy)
	if _, err := g.SpawnAnimal("deer", 45, 45); err != nil {
		t.Fatal(err)
	}
	g.CompleteResearch()
	for i, kind := range []string{"ship structural beam", "ship computer core", "ship stasis casket"} {
		if !g.BuildNow(kind, "steel", "south", 6+6*i, 6) {
			t.Fatalf("could not build the %s", kind)
		}
	}
	g.Step(6000)
	ada, bo := g.pawnIDs[0], g.pawnIDs[1]
	for _, c := range []command.Command{
		{Kind: command.CreateArea},
		{Kind: command.PaintArea, Index: 1, X: 0, Y: 0, X2: 40, Y2: 40, Enabled: true},
		{Kind: command.AssignArea, Pawn: uint64(ada), Index: 1},
		{Kind: command.SetFoodPolicy, Pawn: uint64(ada), Index: 2},
		{Kind: command.SetDrugPolicy, Pawn: uint64(bo), Mode: uint8(drug.Unrestricted)},
		{Kind: command.AddBill, X: 39, Y: 24, Recipe: 1, Mode: uint8(recipe.DoCount), Count: 3},
		{Kind: command.AddOperation, Pawn: uint64(bo), Index: int(body.Amputate), Build: uint8(body.LegL)},
	} {
		g.Enqueue(c)
	}
	addWound(t, g, ada, body.LegL, 4, body.Cut)
	g.ForceBreak(bo, mentalbreak.SadWander)
	g.DevSetPair(ada, bo, "lover")
	g.DevAddOpinionMemory(ada, bo, "insulted")
	g.SetWeather(weather.Snow, 1)
	for _, key := range []string{"trader_caravan", "solar_flare", "flu"} {
		if !g.FireIncident(key) {
			t.Fatalf("incident %s did not fire", key)
		}
	}
	g.combat.Blasts.Explode(0, weapon.MortarSmoke, 50, 10, weapon.DefOf(weapon.MortarSmoke).Blast)
	g.Step(600)
	g.RaidArmed()
	g.RaidMechs(200)
	g.Step(1500)
	m := newMapState(Config{Width: 16, Height: 10}, 1)
	m.tile = 42
	g.maps, g.mapState = append(g.maps, m), m
	initMapHosts(g)
	g.SpawnStack(item.Wood, 10, 7, 7)
	g.BuildNow("wall", "wood", "south", 5, 5)
	if _, err := g.SpawnAnimal("deer", 12, 8); err != nil {
		t.Fatal(err)
	}
	g.mapState = g.view
	g.Step(300) // the new map's heat pass builds its rooms, as a load does
	if !g.startFire(10, 45, 50) {
		t.Fatal("the fire did not start")
	}
	g.Step(1)
	return g
}

func mustCrop(t *testing.T, name string) uint8 {
	t.Helper()
	id, ok := CropID(name)
	if !ok {
		t.Fatalf("no crop %q", name)
	}
	return id
}

// writeSaveV12Fixture regenerates the fixture, which is right only while
// SaveVersion is 12. Once a later version exists the file is frozen, and
// v12Colony and this function can go.
func writeSaveV12Fixture(t *testing.T) {
	t.Helper()
	if SaveVersion != 12 {
		t.Fatalf("%s writes a save of the current version, %d: v12.sav must stay a v12 save", saveV12Env, SaveVersion)
	}
	g := v12Colony(t)
	var buf bytes.Buffer
	if err := g.Save(&buf, "v12"); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(saveV12Fixture, buf.Bytes(), 0o644); err != nil {
		t.Fatal(err)
	}
	t.Logf("%s: %d bytes, state hash %#x", saveV12Fixture, buf.Len(), g.StateHash())
}

// TestSaveV12Fixture loads the checked-in v12 save, so a change that cannot
// read today's saves fails here for as long as v12 is supported.
func TestSaveV12Fixture(t *testing.T) {
	if os.Getenv(saveV12Env) != "" {
		writeSaveV12Fixture(t)
	}
	t.Parallel()
	data, err := os.ReadFile(saveV12Fixture)
	if err != nil {
		t.Fatal(err)
	}
	g, info, err := Load(bytes.NewReader(data))
	if err != nil || info.Version != 12 {
		t.Fatalf("load: %v (info %+v)", err, info)
	}
	if !g.hasSetup() || info.MapSize != 60 || info.Colonists == 0 {
		t.Fatalf("fixture header %+v, has setup %v", info, g.hasSetup())
	}
	hash := g.StateHash()
	if hash != saveV12Hash {
		t.Fatalf("the v12 fixture loads to state hash %#x, pinned %#x. A v12 save must keep loading to the same state: fix the change that moved it. Re-pin only for a migration that means to change a v12 save, and say why in the commit", hash, saveV12Hash)
	}
	h, _ := saveLoadInfo(t, g)
	if got := h.StateHash(); got != hash {
		t.Fatalf("saved again and loaded, state hash %#x, want %#x", got, hash)
	}
	g.Step(600)
	h.Step(600)
	if a, b := g.StateHash(), h.StateHash(); a != b {
		t.Fatalf("the fixture does not continue identically after a re-save: %#x vs %#x", a, b)
	}
}
