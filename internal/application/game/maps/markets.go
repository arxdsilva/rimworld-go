// wiki: Trade, Faction base: a visited settlement restocks after 30 days,
// and trading there gives 2% trade price improvement.
const (
	settlementRestockTicks = 30 * clock.TicksPerDay
	settlementPriceCenti   = 200
)

// SettlementStock is one world's authoritative, shared faction-base stock.
// Preserved stores the actual properties of goods sold to the settlement;
// entries generated by the base's stock definition have default properties.
type SettlementStock struct {
	Tile, FactionID int
	Stock           trade.Stock
	RestockAt       uint64
	Epoch           uint64
	Preserved       []item.Stack
}

func (m SettlementStock) Clone() SettlementStock {
	m.Stock.Lines = trade.CloneLines(m.Stock.Lines)
	m.Preserved = slices.Clone(m.Preserved)
	return m
}

// CloneMarkets copies every market, including its mutable stock and
// preserved physical items, for a save or a restored world.
func CloneMarkets(markets []SettlementStock) []SettlementStock {
	if len(markets) == 0 {
		return nil
	}
	out := make([]SettlementStock, len(markets))
	for i, m := range markets {
		out[i] = m.Clone()
	}
	return out
}

// Markets owns one world's tile-sorted inventories and deferred old-save recovery.
type Markets struct {
	entries     []SettlementStock
	recoveryDue bool
}

// Restore detaches saved stock and notes that visiting caravans from older
// saves require a one-time market reconstruction during the next command pass.
func (m *Markets) Restore(saved []SettlementStock, hadCaravans bool) {
	m.entries = CloneMarkets(saved)
	m.recoveryDue = len(saved) == 0 && hadCaravans
}

// Snapshot contains no aliases to the live market inventory or its physical lots.
func (m *Markets) Snapshot() []SettlementStock { return CloneMarkets(m.entries) }

func (m *Markets) Len() int { return len(m.entries) }

func (m *Markets) RestorationPending() bool { return m.recoveryDue }

// index locates a market without copying it. Mutations remain inside maps.
func (m *Markets) index(tile int) (int, bool) {
	return slices.BinarySearchFunc(m.entries, tile, func(m SettlementStock, t int) int {
		if m.Tile < t {
			return -1
		}
		if m.Tile > t {
			return 1
		}
		return 0
	})
}

// At returns an independent read snapshot of a settlement's stock.
func (m *Markets) At(tile int) (SettlementStock, bool) {
	i, ok := m.index(tile)
	if !ok {
		return SettlementStock{}, false
	}
	return m.entries[i].Clone(), true
}

// Market binds the settlement inventory lifecycle and trade to the
// current world's authoritative caravan fleet.
type Market struct{ fleet Fleet }

// At returns a market snapshot for views without exposing live stock.
func (s Market) At(tile int) (SettlementStock, bool) {
	if s.fleet.market == nil {
		return SettlementStock{}, false
	}
	return s.fleet.market.At(tile)
}

// Visit derives the settlement seed at the native map boundary.
func (s Market) Visit(tile int, fa *faction.Faction, now uint64) {
	if s.fleet.market == nil {
		return
	}
	seed := uint64(0)
	if p := s.fleet.h.Planet(); p != nil {
		seed = p.Seed
	}
	s.fleet.market.visit(tile, fa, now, seed)
}

// visit mutates only the world's market stock. RNG depends on the
// planet seed, tile and restock epoch, not an unrelated simulation stream.
func (m *Markets) visit(tile int, fa *faction.Faction, now, seed uint64) {
	if fa == nil || fa.Defeated || !fa.Type.Human() || fa.Relation == faction.Hostile {
		return
	}
	i, ok := m.index(tile)
	epoch, restockAt := uint64(0), now+settlementRestockTicks
	if ok {
		cur := m.entries[i]
		if cur.FactionID == fa.ID && now < cur.RestockAt {
			return
		}
		epoch, restockAt = cur.Epoch, cur.RestockAt
		if cur.FactionID != fa.ID {
			epoch, restockAt = 0, now+settlementRestockTicks
		} else {
			advance := uint64(1) + (now-restockAt)/settlementRestockTicks
			epoch += advance
			restockAt += advance * settlementRestockTicks
		}
	}
	seed = randx.Mix64(seed ^ randx.Mix64(uint64(tile)+0x736574746c65) ^ randx.Mix64(epoch+0x6d61726b6574))
	stock := SettlementStock{
		Tile: tile, FactionID: fa.ID, Epoch: epoch, RestockAt: restockAt,
		Stock: trade.GenerateSettlement(faction.DefOf(fa.Type).Tech, seed),
	}
	if ok {
		m.entries[i] = stock
	} else {
		m.entries = slices.Insert(m.entries, i, stock)
	}
}

func (s Market) clear(tile int) {
	if s.fleet.market != nil {
		s.fleet.market.clear(tile)
	}
}

func (m *Markets) clear(tile int) {
	if i, ok := m.index(tile); ok {
		m.entries = slices.Delete(m.entries, i, i+1)
	}
}

// RestoreVisits backfills markets missing from saves written before
// settlement inventories existed. Only live visits are considered; the
// initial stock is seeded at the original arrival tick.
func (s Market) RestoreVisits(now uint64) {
	if s.fleet.market == nil || !s.fleet.market.recoveryDue {
		return
	}
	s.fleet.market.recoveryDue = false
	for i := range *s.fleet.list {
		c := &(*s.fleet.list)[i]
		if c.Back || c.C.State != caravan.Visiting || c.Ask.Letter != 0 || now >= c.C.VisitUntil {
			continue
		}
		tile := c.C.Tile
		if _, ok := s.fleet.market.index(tile); ok {
			continue
		}
		fa := s.fleet.h.Faction(tile)
		if fa == nil || fa.Defeated || fa.Besieged || fa.Relation == faction.Hostile ||
			!fa.Type.Human() || !slices.Contains(fa.Settlements, tile) {
			continue
		}
		start := uint64(0)
		if c.C.VisitUntil > clock.TicksPerDay {
			start = c.C.VisitUntil - clock.TicksPerDay
		}
		s.Visit(tile, fa, start)
		s.Visit(tile, fa, now)
	}
}

// RefreshVisits advances only markets whose live visitors can use them.
func (s Market) RefreshVisits(now uint64) {
	if s.fleet.market == nil {
		return
	}
	for i := range *s.fleet.list {
		c := &(*s.fleet.list)[i]
		if c.Back || c.C.State != caravan.Visiting || c.Ask.Letter != 0 || now >= c.C.VisitUntil {
			continue
		}
		j, ok := s.fleet.market.index(c.C.Tile)
		if ok && s.fleet.market.entries[j].RestockAt > now {
			continue
		}
		fa := s.fleet.h.Faction(c.C.Tile)
		if fa == nil || fa.Besieged || !slices.Contains(fa.Settlements, c.C.Tile) {
			continue
		}
		s.Visit(c.C.Tile, fa, now)
	}
}
