// animalSpriteKeys is every sprite the renderer can ask for one body set of
// a species: base is "animal/<key>" or "animal/<key>_f" for the female set.
func animalSpriteKeys(base, attack string) []string {
	var keys []string
	for f := faceSouth; f <= faceWest; f++ {
		stand := base + "_" + f.String()
		keys = append(keys, stand)
		for i := 1; i <= trotFrames; i++ {
			keys = append(keys, fmt.Sprintf("%s_walk%02d", stand, i))
		}
		for i := 1; i <= 4; i++ {
			keys = append(keys, fmt.Sprintf("%s_%s%d", stand, attack, i))
		}
		for _, p := range []string{"graze1", "graze2", "flinch1", "flinch2"} {
			keys = append(keys, stand+"_"+p)
		}
	}
	return keys
}

// TestEverySpeciesHasArt: every species in the roster ships the full body
// set (four facings of stand, trot, its attack kind, graze and flinch),
// three corpse poses and an icon; dimorphic species add the female set.
func TestEverySpeciesHasArt(t *testing.T) {
	root, err := LocateArt()
	if err != nil {
		t.Skip("generated art not present:", err)
	}
	c, err := loadArtCatalog(root)
	if err != nil {
		t.Fatal(err)
	}
	for _, s := range animal.All() {
		ro := animal.RosterOf(s)
		keys := animalSpriteKeys("animal/"+ro.Key, ro.Attack.String())
		if ro.Dimorphic {
			keys = append(keys, animalSpriteKeys("animal/"+ro.Key+"_f", ro.Attack.String())...)
		}
		for v := 0; v < 3; v++ {
			keys = append(keys, fmt.Sprintf("item/corpse_%s_v%d", ro.Key, v))
		}
		keys = append(keys, "ui_icon/"+ro.Key)
		var missing []string
		for _, k := range keys {
			if !c.has(k) {
				missing = append(missing, k)
			}
		}
		if len(missing) > 0 {
			t.Errorf("%s: %d missing sprites, e.g. %s", ro.Key, len(missing), missing[0])
		}
	}
}

// TestGeneratedArtCoversRenderer guards against renderer/art drift: every
// sprite key the draw path can request must exist in assets/.
func TestGeneratedArtCoversRenderer(t *testing.T) {
	root, err := LocateArt()
	if err != nil {
		t.Skip("generated art not present:", err)
	}
	c, err := loadArtCatalog(root)
	if err != nil {
		t.Fatal(err)
	}
	var keys []string
	for v := 0; v < soilVariants; v++ {
		keys = append(keys, artKey("terrain", "soil", v))
	}
	for m := 0; m < 16; m++ {
		keys = append(keys, "structure/wall_wood_"+twoDigits(m))
	}
	keys = append(keys, "plant/grass_short_v0", "plant/grass_short_v1", "plant/bush_mature_v0", "plant/bush_mature_v1",
		"plant/berry_bush_harvestable_v0", "plant/berry_bush_harvestable_v1", "overlay/grow_zone",
		"plant/crop_sown",
		itemSprite("food"), itemSprite("berries"), itemSprite("meat"),
		itemSprite("meal"), itemSprite("stone"), "rock/rock_wall_15", "terrain/stone_edge_15",
		"structure/wall_stone_15", "structure/floor_stone",
		"structure/frame_1x1", "item/wood_pile", "item/food_crate", "overlay/stockpile",
		"overlay/blueprint", "overlay/selection", "overlay/designation_harvest",
		"overlay/designation_deconstruct", "ui_icon/draft", "overlay/designation_hunt",
		"weapon/rifle_basic",
		"tool/hammer", "tool/axe", "tool/pickaxe",
		"overlay/sleeping_spot_south", "overlay/sleeping_spot_east", "overlay/sleeping_spot_north",
		"overlay/sleeping_spot_west", "ui_icon/sleeping_spot")
	for _, c := range game.Crops() {
		for _, st := range []string{"young", "mature", "harvestable"} {
			keys = append(keys, "plant/"+c.Name+"_"+st)
		}
		keys = append(keys, itemSprite(c.Label), "ui_icon/"+strings.ReplaceAll(c.Label, " ", "_"))
	}
	for _, t := range archTools {
		keys = append(keys, "ui_icon/"+t.icon)
		if t.build == "" {
			continue
		}
		for _, f := range facingNames {
			for _, open := range []bool{false, true} {
				for _, ew := range []bool{false, true} {
					keys = append(keys, buildSprite(t.build, f, 0, ew, open))
				}
			}
		}
	}
	// ART-015: every baked variant a linked family can be asked for, and
	// the stone, ore and smoothing singles.
	for _, prefix := range []string{"rock/rock_wall", "rock/rock_smooth", "rock/ore_steel", "rock/ore_silver", "rock/ore_gold",
		"rock/ore_machinery", "structure/wall_wood", "structure/wall_stone", "structure/wall_steel"} {
		keys = append(keys, linkedKeys(prefix)...)
	}
	for _, ew := range []bool{false, true} {
		for _, open := range []bool{false, true} {
			keys = append(keys, buildSpriteStuff("door", "steel", "", 0, ew, open))
		}
	}
	for v := 0; v < soilVariants; v++ {
		keys = append(keys, artKey("terrain", "stone_smooth", v))
	}
	for m := 1; m < 16; m++ {
		keys = append(keys, "terrain/stone_smooth_edge_"+twoDigits(m))
	}
	keys = append(keys, itemSprite("granite chunk"), itemSprite("marble blocks"), itemSprite("steel"),
		itemSprite("silver"), itemSprite("gold"), smoothMarkKey)
	keys = append(keys, ng1ArtKeys()...) // water, mud, track, caves, pods, components, medicine, cabinet, hospital bed
	for f := faceSouth; f <= faceWest; f++ {
		for _, l := range []string{"body", "pants_basic", "shirt_basic", "vest_utility", "parka_leather", "duster_leather"} {
			keys = append(keys, "pawn/"+l+"_"+f.String())
			for i := 1; i <= walkFrames; i++ {
				keys = append(keys, fmt.Sprintf("pawn/%s_%s_walk%02d", l, f, i))
			}
			for i := 1; i <= workFrames; i++ {
				keys = append(keys, fmt.Sprintf("pawn/%s_%s_work%d", l, f, i))
			}
		}
		for _, bed := range []string{"bed_basic"} {
			keys = append(keys, "furniture/"+bed+"_blanket_"+f.String())
		}
		for _, h := range hairStyles {
			keys = append(keys, "pawn/"+h+"_"+f.String())
		}
	}
	for _, k := range treePartCoverageKeys() { // PLAY-010 2.9: whole tree plus its trunk and canopy parts
		keys = append(keys, k, k+treeTrunkSuffix, k+treeCanopySuffix)
	}
	for _, k := range keys {
		if !c.has(k) {
			t.Errorf("missing generated sprite %s", k)
		}
	}
	if n := len(c.tintNames("stone_tint")); n != len(stoneNames)-1 {
		t.Errorf("stone_tint has %d presets, want one per stone (%d)", n, len(stoneNames)-1)
	}
	for _, o := range []string{"steel", "silver", "gold"} { // the ore body takes the stone tint through a mask
		if sp := c.sprite("rock/ore_" + o + "_15_cf"); sp != nil && (sp.mask == nil || sp.meta.TintGroup == "") {
			t.Errorf("rock/ore_%s should be tintable", o)
		}
	}
	for _, g := range []string{"skin", "hair", "cloth"} {
		if len(c.tintNames(g)) == 0 {
			t.Errorf("no %s tint presets in palettes/base.yaml", g)
		}
	}
	for _, k := range []string{"pawn/body_south", "pawn/hair_bun_east", "furniture/bed_basic_west"} {
		sp := c.sprite(k)
		if sp.mask == nil || sp.meta.TintGroup == "" {
			t.Errorf("%s should be tintable", k)
		}
		if sp.pix.Bounds().Dx() != sp.meta.Canvas[0] || sp.pix.Bounds().Dy() != sp.meta.Canvas[1] {
			t.Errorf("%s: png %v != canvas %v", k, sp.pix.Bounds().Size(), sp.meta.Canvas)
		}
	}
}

func TestArtFrameNames(t *testing.T) {
	t.Parallel()
	if walkFrames != 12 || workFrames != 6 || trotFrames != 8 {
		t.Fatal("C5: 12 walk, 6 work, 8 trot frames")
	}
	m, err := parseArtMeta(sampleMeta + "  head: [96.5, 60.0]\n")
	if err != nil {
		t.Fatal(err)
	}
	if m.Attach["head"] != [2]float64{96.5, 60} || m.Attach["hand"] != [2]float64{103, 176.4} {
		t.Fatalf("head attaches beside hand: %v", m.Attach)
	}
	// frames from before the head attachment still parse; head is simply absent
	old, err := parseArtMeta(sampleMeta)
	if err != nil {
		t.Fatal(err)
	}
	if _, ok := old.Attach["head"]; ok {
		t.Fatal("no head in old metadata")
	}
	c := &artCatalog{sprites: map[string]*artSprite{"pawn/body_south": {}, "pawn/body_south_walk03": {}}}
	r := &Renderer{art: c}
	if r.framed("pawn/body_south", "_walk03") != "pawn/body_south_walk03" {
		t.Fatal("new frame names resolve")
	}
	if r.framed("pawn/body_south", "_walk04") != "pawn/body_south" {
		t.Fatal("missing frames fall back to the static pose")
	}
}
