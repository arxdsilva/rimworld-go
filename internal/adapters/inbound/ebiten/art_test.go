// TestGeneratedArtCoversRenderer guards against renderer/art drift: every
// sprite key the draw path can request must exist in assets/.
func TestGeneratedArtCoversRenderer(t *testing.T) {
	root, err := LocateArt()
	if err != nil {
		t.Skip("generated art not present:", err)
	}
	c, err := loadArtCatalog(root)
	if err != nil {
		t.Fatal(err)
	}
	var keys []string
	for v := 0; v < soilVariants; v++ {
		keys = append(keys, artKey("terrain", "soil", v))
	}
	for m := 0; m < 16; m++ {
		keys = append(keys, "structure/wall_wood_"+twoDigits(m))
	}
	keys = append(keys, "plant/grass_00", "plant/grass_01", "plant/bush_00", "plant/bush_01",
		"plant/bush_00_harvestable", "plant/bush_01_harvestable", "overlay/grow_zone",
		"plant/crop_sown", "plant/crop_young", "plant/crop_mature", "plant/crop_harvestable",
		itemSprite("food"), itemSprite("berries"), itemSprite("amberroot"), itemSprite("meat"),
		itemSprite("meal"), itemSprite("stone"), "rock/rock_wall_15", "terrain/stone_edge_15",
		"structure/wall_stone_15", "structure/floor_stone",
		"structure/frame_1x1", "item/wood_pile", "item/food_crate", "overlay/stockpile",
		"overlay/blueprint", "overlay/selection", "overlay/designation_harvest",
		"overlay/designation_deconstruct", "ui_icon/draft", "overlay/designation_hunt",
		"weapon/rifle_basic", "ui_icon/dustbuck", "ui_icon/ridgewolf")
	for _, sp := range []string{"dustbuck", "ridgewolf"} {
		for f := faceSouth; f <= faceWest; f++ {
			keys = append(keys, "animal/"+sp+"_"+f.String())
		}
	}
	for _, t := range archTools {
		keys = append(keys, "ui_icon/"+t.icon)
		if t.build == "" {
			continue
		}
		for _, f := range facingNames {
			for _, open := range []bool{false, true} {
				for _, ew := range []bool{false, true} {
					keys = append(keys, buildSprite(t.build, f, 0, ew, open))
				}
			}
		}
	}
	for f := faceSouth; f <= faceWest; f++ {
		for _, l := range []string{"body", "pants_basic", "shirt_basic", "vest_utility"} {
			keys = append(keys, "pawn/"+l+"_"+f.String())
		}
		for _, h := range hairStyles {
			keys = append(keys, "pawn/"+h+"_"+f.String())
		}
	}
	for _, k := range keys {
		if !c.has(k) {
			t.Errorf("missing generated sprite %s", k)
		}
	}
	for _, g := range []string{"skin", "hair", "cloth"} {
		if len(c.tintNames(g)) == 0 {
			t.Errorf("no %s tint presets in palettes/base.yaml", g)
		}
	}
	for _, k := range []string{"pawn/body_south", "pawn/hair_bun_east", "furniture/bed_cot_west"} {
		sp := c.sprite(k)
		if sp.mask == nil || sp.meta.TintGroup == "" {
			t.Errorf("%s should be tintable", k)
		}
		if sp.pix.Bounds().Dx() != sp.meta.Canvas[0] || sp.pix.Bounds().Dy() != sp.meta.Canvas[1] {
			t.Errorf("%s: png %v != canvas %v", k, sp.pix.Bounds().Size(), sp.meta.Canvas)
		}
	}
}
