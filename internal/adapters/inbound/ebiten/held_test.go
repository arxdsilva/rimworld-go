var standPose = pose{px: figurePivotX, py: figurePivotY}

// bodyPoint is a body attachment on screen for a figure at (wx, wy).
func bodyPoint(r *Renderer, f facing, sfx, name string, wx, wy, tile float64) pt {
	body := r.art.sprite(r.framed("pawn/body_"+f.String(), sfx))
	sx, sy := r.worldToScreenF(wx, wy)
	bx, by, s := artOrigin(body.meta, float64(sx), float64(sy), tile)
	a := body.meta.Attach[name]
	return pt{bx + a[0]*s, by + a[1]*s}
}

func apply(g ebiten.GeoM, p pt) pt {
	x, y := g.Apply(p[0], p[1])
	return pt{x, y}
}

func det(g ebiten.GeoM) float64 {
	return g.Element(0, 0)*g.Element(1, 1) - g.Element(0, 1)*g.Element(1, 0)
}

func TestHeldTwoHandSolve(t *testing.T) {
	t.Parallel()
	r := artRenderer()
	const tile = 64.0
	for f := faceSouth; f <= faceWest; f++ {
		for _, key := range []string{"weapon/rifle_basic", "weapon/spear"} {
			sp := r.art.sprite(key)
			g, _, ok := r.heldGeo(f, "_aim", heldItem{key: key, stance: stanceHands}, false, 3, 4, tile, standPose)
			if !ok {
				t.Fatalf("%v %s: no placement", f, key)
			}
			hand := bodyPoint(r, f, "_aim", "hand", 3, 4, tile)
			handL := bodyPoint(r, f, "_aim", "hand_l", 3, 4, tile)
			grip := apply(g, sp.meta.Attach["grip"])
			if math.Hypot(grip[0]-hand[0], grip[1]-hand[1]) > 1 {
				t.Fatalf("%v %s: grip %v not on hand %v", f, key, grip, hand)
			}
			sup := apply(g, sp.meta.Attach["support"])
			dx, dy := handL[0]-hand[0], handL[1]-hand[1]
			n := math.Hypot(dx, dy)
			off := math.Abs((sup[0]-hand[0])*dy-(sup[1]-hand[1])*dx) / n
			along := ((sup[0]-hand[0])*dx + (sup[1]-hand[1])*dy) / n
			if off > 1 || along <= 0 {
				t.Fatalf("%v %s: support %v off the hand->hand_l line by %.2fpx (along %.2f)", f, key, sup, off, along)
			}
			if mirrored := det(g) < 0; mirrored != (f == faceWest) {
				t.Fatalf("%v %s: mirrored=%v, want only west", f, key, mirrored)
			}
		}
	}
	// a body frame without hand_l (older art) still holds the item at the hand
	c := r.art
	c.sprites["pawn/body_east_work3"] = fakeSprite([2]int{160, 297}, pt{16, 153}, map[string]pt{"hand": {101.9, 111.6}, "head": {82, 111}})
	if _, _, ok := r.heldGeo(faceEast, "_work3", heldItem{key: "weapon/rifle_basic", stance: stanceHands}, false, 3, 4, tile, standPose); !ok {
		t.Fatal("no hand_l: fallback placement")
	}
}

func TestOffHandItemAtHandL(t *testing.T) {
	t.Parallel()
	r := artRenderer()
	const tile = 64.0
	h := heldItem{set: true, key: "tool/spoon", stance: stanceUpright, off: "tool/bowl"}
	for _, f := range []facing{faceEast, faceWest} {
		g, key, ok := r.heldGeo(f, "", h, true, 2, 2, tile, standPose)
		if !ok || key != "tool/bowl" {
			t.Fatalf("%v: bowl not placed (%q)", f, key)
		}
		grip := apply(g, r.art.sprite("tool/bowl").meta.Attach["grip"])
		handL := bodyPoint(r, f, "", "hand_l", 2, 2, tile)
		if math.Hypot(grip[0]-handL[0], grip[1]-handL[1]) > 1 {
			t.Fatalf("%v: bowl grip %v not at hand_l %v", f, grip, handL)
		}
		if math.Abs(g.Element(1, 0)) > 1e-9 {
			t.Fatalf("%v: the bowl is held level", f)
		}
		if mirrored := det(g) < 0; mirrored != (f == faceWest) {
			t.Fatalf("%v: mirrored=%v", f, mirrored)
		}
	}
	// the right-hand spoon hangs along the forearm (down at rest)
	g, _, ok := r.heldGeo(faceEast, "", h, false, 2, 2, tile, standPose)
	sp := r.art.sprite("tool/spoon").meta.Attach
	head, grip := apply(g, sp["head"]), apply(g, sp["grip"])
	if !ok || head[1] <= grip[1] {
		t.Fatalf("spoon along the hanging forearm: grip %v head %v", grip, head)
	}
	// left arm sides mirror the right: far arm facing east, near facing west
	if !heldBehind(stanceUpright, faceEast, true) || heldBehind(stanceUpright, faceWest, true) {
		t.Fatal("left-hand item: behind facing east, in front facing west")
	}
	if heldBehind(stanceUpright, faceEast, false) || !heldBehind(stanceUpright, faceWest, false) {
		t.Fatal("right-hand item: in front facing east, behind facing west")
	}
	// no hand_l in the frame: nothing in the left hand
	r.art.sprites["pawn/body_east_old"] = fakeSprite([2]int{160, 297}, pt{16, 153}, map[string]pt{"hand": {98, 175}})
	if _, _, ok := r.heldGeo(faceEast, "_old", h, true, 2, 2, tile, standPose); ok {
		t.Fatal("left item needs hand_l")
	}
}

func TestRifleSlungWhenUndrafted(t *testing.T) {
	t.Parallel()
	r := artRenderer()
	p := game.PawnView{ID: 1, Weapon: "rifle"}
	h := r.idleHeld(p, moveState{})
	if h.key != "weapon/rifle_slung" || h.stance != stanceSlung {
		t.Fatalf("off duty the rifle is slung: %+v", h)
	}
	for _, q := range []game.PawnView{
		{Weapon: "rifle", Drafted: true},
		{Weapon: "rifle", Action: game.ActionAim},
		{Weapon: "rifle", Hostile: true},
	} {
		if h := r.idleHeld(q, moveState{}); h.key != "weapon/rifle_basic" || h.stance != stanceHands || h.angle >= 0 {
			t.Fatalf("on duty (%+v) the rifle is held at low ready: %+v", q, h)
		}
	}
	// on the back: the slung sprite's back point below the head
	g, key, ok := r.heldGeo(faceEast, "", h, false, 2, 2, 64, standPose)
	if !ok || key != "weapon/rifle_slung" {
		t.Fatal("slung placement")
	}
	back := apply(g, r.art.sprite(key).meta.Attach["back"])
	head := bodyPoint(r, faceEast, "", "head", 2, 2, 64)
	if math.Abs(back[0]-head[0]) > 1 || back[1] <= head[1] {
		t.Fatalf("slung rifle on the back below the head: back %v head %v", back, head)
	}
	if !heldBehind(stanceSlung, faceEast, false) || heldBehind(stanceSlung, faceNorth, false) {
		t.Fatal("slung: behind the body, in front facing north")
	}
	// without the slung sprite the rifle lies across the back
	delete(r.art.sprites, "weapon/rifle_slung")
	if _, key, ok := r.heldGeo(faceWest, "", h, false, 2, 2, 64, standPose); !ok || key != "weapon/rifle_basic" {
		t.Fatal("fallback: the rifle across the back")
	}
}

func TestSpearUprightWhenWalking(t *testing.T) {
	t.Parallel()
	r := artRenderer()
	walking := moveState{Blend: 1, Moving: true, Speed: 0.06}
	h := r.idleHeld(game.PawnView{Weapon: "spear"}, walking)
	if h.key != "weapon/spear" || h.stance != stanceUpright {
		t.Fatalf("off duty the spear is carried upright: %+v", h)
	}
	for _, f := range []facing{faceEast, faceWest, faceSouth} {
		g, _, ok := r.heldGeo(f, "", h, false, 2, 2, 64, standPose)
		sp := r.art.sprite("weapon/spear").meta.Attach
		grip, tip := apply(g, sp["grip"]), apply(g, sp["tip"])
		if !ok || tip[1] >= grip[1]-20 || math.Abs(tip[0]-grip[0]) > 1 {
			t.Fatalf("%v: spear tip straight up: grip %v tip %v", f, grip, tip)
		}
	}
	if h := r.idleHeld(game.PawnView{Weapon: "spear", Drafted: true}, walking); h.stance != stanceHands {
		t.Fatal("drafted: spear in both hands")
	}
}

func TestKnifeNotDrawnWhenIdle(t *testing.T) {
	t.Parallel()
	r := artRenderer()
	if h := r.idleHeld(game.PawnView{Weapon: "knife"}, moveState{}); h.key != "" {
		t.Fatalf("off duty the knife stays on the belt: %+v", h)
	}
	if h := r.idleHeld(game.PawnView{Weapon: "knife", Drafted: true}, moveState{}); h.key != "weapon/knife" || h.stance != stanceHands {
		t.Fatalf("drafted: the knife is drawn: %+v", h)
	}
	if h := r.idleHeld(game.PawnView{Weapon: "club"}, moveState{}); h.key != "weapon/club" {
		t.Fatalf("the club stays in hand: %+v", h)
	}
	if h := r.idleHeld(game.PawnView{Weapon: "fists", Drafted: true}, moveState{}); h.key != "" {
		t.Fatal("fists: nothing held")
	}
	// one-handed: the club hangs along the forearm at rest
	g, _, _ := r.heldGeo(faceEast, "", heldItem{key: "weapon/club", stance: stanceUpright}, false, 2, 2, 64, standPose)
	sp := r.art.sprite("weapon/club").meta.Attach
	if tip, grip := apply(g, sp["tip"]), apply(g, sp["grip"]); tip[1] <= grip[1] {
		t.Fatal("the club hangs down from the hand")
	}
	// the old club sprite stands in until weapon/club exists
	delete(r.art.sprites, "weapon/club")
	r.art.sprites["item/club_wood"] = fakeSprite([2]int{160, 173}, pt{16, 29}, map[string]pt{})
	if _, key, ok := r.heldGeo(faceEast, "", heldItem{key: "weapon/club", stance: stanceUpright}, false, 2, 2, 64, standPose); !ok || key != "item/club_wood" {
		t.Fatal("club fallback sprite")
	}
}

func TestHeldDraws(t *testing.T) {
	t.Parallel()
	r := artRenderer()
	screen := ebiten.NewImage(256, 256)
	items := []heldItem{
		{key: "weapon/rifle_basic", stance: stanceHands, aim: true, aimX: 9, aimY: 2},
		{key: "weapon/rifle_slung", stance: stanceSlung},
		{key: "weapon/spear", stance: stanceUpright},
		{key: "tool/spoon", stance: stanceUpright, off: "tool/bowl"},
		{key: "item/wood_pile", stance: stanceLoad},
	}
	for _, h := range items {
		for f := faceSouth; f <= faceWest; f++ {
			for _, behind := range []bool{true, false} {
				r.drawHeld(screen, game.PawnView{}, f, "", h, 1, 1, 64, standPose, behind)
			}
		}
	}
	// a load sits between the hands
	g, _, ok := r.heldGeo(faceEast, "", items[4], false, 1, 1, 64, standPose)
	mid := apply(g, pt{16 + artTilePx/2, 29 + artTilePx/2})
	hand, handL := bodyPoint(r, faceEast, "", "hand", 1, 1, 64), bodyPoint(r, faceEast, "", "hand_l", 1, 1, 64)
	if !ok || math.Abs(mid[0]-(hand[0]+handL[0])/2) > 1 {
		t.Fatalf("load between the hands: %v", mid)
	}
	if _, ok := r.heldPoint(faceEast, "", heldItem{}, 1, 1, standPose, "hand"); !ok {
		t.Fatal("bare hand point")
	}
}
