#!/usr/bin/env python3
"""Generate compile-time difficulty presets from the project's reviewed JSON."""
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
src = ROOT / "internal/domain/difficulty/presets.json"
dst = ROOT / "internal/domain/difficulty/presets.go"
rows = json.loads(src.read_text(encoding="utf-8"))
keys = ("wanderer", "gentle", "settled", "seasoned", "grim", "merciless")
if tuple(row["key"] for row in rows) != keys:
    raise ValueError("difficulty preset order must match saved Preset IDs")

lines = [
    "// SPDX-License-Identifier: GPL-3.0-only",
    "// Copyright (C) 2026 Arthur Rodrigues Xavier da Silva",
    "",
    "// Code generated by scripts/gen_difficulty_presets.py; DO NOT EDIT.",
    "package difficulty",
    "",
    "// Presets are compiled from presets.json; there is no runtime data loading.",
    "var presets = [Custom]Named{",
]
for row in rows:
    if row.get("source") != "wiki: AI Storytellers; original tuning":
        raise ValueError(f"{row['key']}: source must be a permitted wiki")
    name = row["key"].capitalize()
    lines.append("\t// Mix of published wiki numbers and original project tuning.")
    lines.append(
        f"\t{name}: {{Preset: {name}, Key: {json.dumps(row['key'])}, "
        f"Label: {json.dumps(name)}, Desc: {json.dumps(row['description'])}, Settings: Settings{{"
    )
    wiki_fields = {
        "FriendlyFire", "ThreatScale", "AdaptGrowth", "AdaptStrength", "FoodPoisonChance",
        "CropYield", "MineYield", "ButcherYield", "ResearchSpeed",
        "MoodOffset", "Infection", "DiseaseFreq", "AnimalRevenge",
    }
    for field, value in row["settings"].items():
        if type(value) is bool:
            value = str(value).lower()
        elif type(value) is not int:
            raise ValueError(f"{row['key']}.{field}: unsupported field type")
        provenance = "wiki: AI Storytellers" if field in wiki_fields else "original tuning"
        lines.append(f"\t\t{field}: {value}, // {provenance}")
    lines.append("\t\tBalanceVersion: 3,")
    lines.append("\t}},")
lines.append("}")
dst.write_text("\n".join(lines) + "\n", encoding="utf-8")
subprocess.run(["gofmt", "-w", str(dst)], check=True)
