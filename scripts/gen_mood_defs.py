#!/usr/bin/env python3
"""Generate Go thought definitions from the project's own reviewed data."""
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
directory = ROOT / "internal/domain/pawn/mood"
rows = json.loads((directory / "definitions.json").read_text(encoding="utf-8"))
source = (directory / "mood.go").read_text(encoding="utf-8")
enum = source[source.index("const ("):source.index("numKinds")]
names = []
for line in enum.splitlines()[1:]:
    head = line.split("//", 1)[0].strip()
    if re.fullmatch(r"[A-Za-z]\w*(?:\s+Kind\s*=\s*iota)?", head):
        names.append(head.split()[0])
if len(rows) != len(names) or not rows:
    raise ValueError("definitions count differs from saved Kind enumeration")

def duration(text):
    if text == "0":
        return "0"
    match = re.fullmatch(r"(\d+)([dht])", text)
    if match is None:
        raise ValueError(f"invalid duration {text!r}")
    count, unit = match.groups()
    if unit == "t":
        return count
    symbol = "day" if unit == "d" else "needHour"
    return symbol if count == "1" else f"{count} * {symbol}"

lines = [
    "// SPDX-License-Identifier: GPL-3.0-only",
    "// Copyright (C) 2026 Arthur Rodrigues Xavier da Silva",
    "",
    "// Code generated by scripts/gen_mood_defs.py; DO NOT EDIT.",
    "package mood",
    "",
    "// Saved Kind numbers stay in mood.go; this data is from definitions.json.",
    "var defs = [numKinds]Def{",
]
# WIKI_FAMILY maps each cited wiki page to the CLEAN_ROOM.md exception row
# that admits its numbers; a page with no row fails generation.
WIKI_FAMILY = {
    "Anesthetic": "MED-*", "Body modder": "MED-*", "Body purist": "MED-*", "Joywire": "MED-*",
    "Apparel": "GEAR-*",
    "Food": "FOOD-*", "Human meat": "FOOD-*", "Insect meat": "FOOD-*", "Meals": "FOOD-*", "Saturation": "FOOD-*",
    "Temperature": "TEMP-*", "Toxic fallout": "TEMP-*",
    "Mood": "SIM-071", "Thoughts": "SIM-071", "Thoughts/Memory Misc": "SIM-071", "Wealth": "SIM-071",
    "Thoughts/Memory Social": "ENG-003",
}
ordered = []
for idx, row in enumerate(rows):
    if row["id"] != idx or row["kind"] != names[idx]:
        raise ValueError(f"saved thought ID/order mismatch at {idx}: {row!r}")
    src = row["source"]
    if src != "original tuning" and not src.startswith("wiki: "):
        raise ValueError(f"unknown provenance for {row['kind']}")
    if src.startswith("wiki: "):
        family = WIKI_FAMILY.get(src[len("wiki: "):])
        if family is None:
            raise ValueError(f"{row['kind']}: wiki page {src!r} has no CLEAN_ROOM.md exception family")
        src = f"{src} ({family})"
    group = row["group"]
    if not re.fullmatch(r"group[A-Za-z]+", group):
        raise ValueError(f"invalid group for {row['kind']}")
    val = row["value"]
    limit = row["stack_limit"]
    factor = row["stack_factor"]
    if any(type(n) is not int for n in (val, limit, factor)):
        raise ValueError(f"invalid numeric field for {row['kind']}")
    label = json.dumps(row["label"], ensure_ascii=False)
    lines.append(f"\t// {src}")
    lines.append(f"\t{row['kind']}: {{Label: {label}, Value: {val}, Duration: {duration(row['duration'])}, Group: {group}, StackLimit: {limit}, StackFactor: {factor}}},")
    ordered.append(row["kind"])
lines.append("}")

def snake(name):
    name = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", name)
    return re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name).lower()

# keys are the stable namespaced names ("core.<key>") plugins patch by.
key_of = [snake(n) for n in ordered]
for kind, key in zip(ordered, key_of):
    if re.fullmatch(r"[a-z][a-z0-9_]*", key) is None:
        raise ValueError(f"{kind}: key {key!r} is not lower snake case")
if len(set(key_of)) != len(key_of):
    raise ValueError("thought keys are not unique")
lines.append("")
lines.append("// keys are each thought's stable key, the lower snake case of its Kind.")
lines.append("var keys = [numKinds]string{")
for kind, key in zip(ordered, key_of):
    lines.append(f"\t{kind}: {json.dumps(key)},")
lines.append("}")
(directory / "defs_generated.go").write_text("\n".join(lines) + "\n", encoding="utf-8")

subprocess.run(["gofmt", "-w", str(directory / "defs_generated.go")], check=True)
