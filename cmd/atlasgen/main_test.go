// subimage reads rect out of a page.
func pageRect(t *testing.T, path string, r image.Rectangle) *image.NRGBA {
	t.Helper()
	img, err := decode(path)
	if err != nil {
		t.Fatal(err)
	}
	out := image.NewNRGBA(image.Rectangle{Max: r.Size()})
	for y := 0; y < r.Dy(); y++ {
		copy(out.Pix[out.PixOffset(0, y):out.PixOffset(r.Dx(), y)], img.Pix[img.PixOffset(r.Min.X, r.Min.Y+y):])
	}
	return out
}

func TestPackEveryKeyPresentAndPixelsRoundTrip(t *testing.T) {
	root := t.TempDir()
	specs := sampleSpecs()
	writeFamily(t, root, "pawn", specs)
	res, err := pack(root, "pawn", 64)
	if err != nil {
		t.Fatal(err)
	}
	if res.sprites != len(specs) || res.pages < 2 {
		t.Fatalf("packed %d sprites in %d pages, want %d in several", res.sprites, res.pages, len(specs))
	}
	raw, err := os.ReadFile(filepath.Join(root, "metadata", "atlas", "pawn.yaml"))
	if err != nil {
		t.Fatal(err)
	}
	idx, err := parseAtlas(string(raw))
	if err != nil {
		t.Fatal(err)
	}
	byKey := map[string]atlasSprite{}
	for _, s := range idx.list {
		byKey[s.key] = s
	}
	for _, sp := range specs {
		s, ok := byKey[sp.key]
		if !ok {
			t.Fatalf("key %s missing from the atlas", sp.key)
		}
		if s.mask != sp.tinted || s.normal != sp.normal {
			t.Errorf("%s: mask/normal flags %v/%v, want %v/%v", sp.key, s.mask, s.normal, sp.tinted, sp.normal)
		}
		// the trim is exactly the opaque block
		if want := sp.block; s.rect.Size() != want.Size() || s.trim != want.Min {
			t.Errorf("%s: rect %v trim %v, want size %v at %v", sp.key, s.rect, s.trim, want.Size(), want.Min)
		}
		// pixels round-trip through the page
		orig, err := decode(filepath.Join(root, "generated", "world", "pawn", sp.key+".png"))
		if err != nil {
			t.Fatal(err)
		}
		page := pageRect(t, filepath.Join(root, "generated", "atlas", fmt.Sprintf("pawn_%d.png", s.page)), s.rect)
		for y := 0; y < s.rect.Dy(); y++ {
			for x := 0; x < s.rect.Dx(); x++ {
				if got, want := page.NRGBAAt(x, y), orig.NRGBAAt(s.trim.X+x, s.trim.Y+y); got != want {
					t.Fatalf("%s: pixel (%d,%d) = %v, want %v", sp.key, x, y, got, want)
				}
			}
		}
		if sp.tinted {
			mask := pageRect(t, filepath.Join(root, "generated", "atlas", fmt.Sprintf("pawn_%d_mask.png", s.page)), s.rect)
			om, _ := decode(filepath.Join(root, "generated", "world", "pawn", sp.key+"_mask.png"))
			for y := 0; y < s.rect.Dy(); y++ {
				for x := 0; x < s.rect.Dx(); x++ {
					if got, want := mask.NRGBAAt(x, y).R, om.NRGBAAt(s.trim.X+x, s.trim.Y+y).R; got != want {
						t.Fatalf("%s: mask (%d,%d) = %d, want %d", sp.key, x, y, got, want)
					}
				}
			}
		}
		if sp.normal {
			n := pageRect(t, filepath.Join(root, "generated", "atlas", fmt.Sprintf("pawn_%d_n.png", s.page)), s.rect)
			on, _ := decode(filepath.Join(root, "generated", "world", "pawn", sp.key+"_n.png"))
			// the page keeps RGB and is opaque; the alpha is the sprite's
			if got, want := n.NRGBAAt(2, 2), on.NRGBAAt(s.trim.X+2, s.trim.Y+2); got != want {
				t.Fatalf("%s: normal = %v, want %v", sp.key, got, want)
			}
		}
	}
	// the sprite metadata is carried over, with image/mask pointing at the pages
	text := string(raw)
	for _, want := range []string{"    attachments:\n      hand: [1.5, 2.5]\n", "    origin_px: [16, 153]\n",
		"    image: generated/atlas/pawn_", "      mask: generated/atlas/pawn_", "    canvas: [40, 50]\n"} {
		if !strings.Contains(text, want) {
			t.Errorf("atlas yaml lacks %q", want)
		}
	}
	if errs := checkAtlas(root, "pawn", 64); len(errs) != 0 {
		t.Fatalf("a fresh atlas fails -check: %v", errs)
	}
}

func readTree(t *testing.T, root string) map[string][]byte {
	t.Helper()
	out := map[string][]byte{}
	for _, dir := range []string{"generated/atlas", "metadata/atlas"} {
		files, err := os.ReadDir(filepath.Join(root, dir))
		if err != nil {
			t.Fatal(err)
		}
		for _, f := range files {
			b, err := os.ReadFile(filepath.Join(root, dir, f.Name()))
			if err != nil {
				t.Fatal(err)
			}
			out[dir+"/"+f.Name()] = b
		}
	}
	return out
}

func TestPackIsDeterministic(t *testing.T) {
	specs := sampleSpecs()
	a, b := t.TempDir(), t.TempDir()
	writeFamily(t, a, "pawn", specs)
	writeFamily(t, b, "pawn", specs)
	for _, root := range []string{a, b, a} { // a twice: re-packing over its own output
		if _, err := pack(root, "pawn", 100); err != nil {
			t.Fatal(err)
		}
	}
	ta, tb := readTree(t, a), readTree(t, b)
	if len(ta) != len(tb) || len(ta) < 3 {
		t.Fatalf("file sets differ: %d vs %d", len(ta), len(tb))
	}
	names := make([]string, 0, len(ta))
	for n := range ta {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		if !bytes.Equal(ta[n], tb[n]) {
			t.Errorf("%s differs between runs", n)
		}
	}
}

func TestPackRemovesStalePages(t *testing.T) {
	root := t.TempDir()
	writeFamily(t, root, "pawn", sampleSpecs())
	if _, err := pack(root, "pawn", 64); err != nil {
		t.Fatal(err)
	}
	before := len(readTree(t, root))
	// pack the same family bigger: fewer pages, none left over from the first run
	if _, err := pack(root, "pawn", 512); err != nil {
		t.Fatal(err)
	}
	if after := len(readTree(t, root)); after >= before {
		t.Fatalf("stale pages kept: %d files before, %d after", before, after)
	}
	if errs := checkAtlas(root, "pawn", 512); len(errs) != 0 {
		t.Fatal(errs)
	}
}

func TestCheckDetectsMissingKey(t *testing.T) {
	root := t.TempDir()
	writeFamily(t, root, "pawn", sampleSpecs())
	if _, err := pack(root, "pawn", 128); err != nil {
		t.Fatal(err)
	}
	mp := filepath.Join(root, "metadata", "atlas", "pawn.yaml")
	raw, _ := os.ReadFile(mp)
	// drop the block of body_05
	var kept []string
	skip := false
	for _, line := range strings.Split(string(raw), "\n") {
		if strings.HasPrefix(line, "  ") && !strings.HasPrefix(line, "   ") {
			skip = line == "  body_05:"
		}
		if !skip {
			kept = append(kept, line)
		}
	}
	if err := os.WriteFile(mp, []byte(strings.Join(kept, "\n")), 0o644); err != nil {
		t.Fatal(err)
	}
	errs := checkAtlas(root, "pawn", 128)
	if len(errs) != 1 || !strings.Contains(errs[0].Error(), "body_05") {
		t.Fatalf("errs = %v, want exactly the missing body_05", errs)
	}
}

func TestCheckDetectsBrokenAtlases(t *testing.T) {
	pack1 := func(t *testing.T) (string, string) {
		root := t.TempDir()
		writeFamily(t, root, "pawn", sampleSpecs())
		if _, err := pack(root, "pawn", 128); err != nil {
			t.Fatal(err)
		}
		return root, filepath.Join(root, "metadata", "atlas", "pawn.yaml")
	}
	t.Run("no atlas", func(t *testing.T) {
		if errs := checkAtlas(t.TempDir(), "pawn", 128); len(errs) == 0 {
			t.Fatal("want an error for a missing atlas")
		}
	})
	t.Run("overlap", func(t *testing.T) {
		root, mp := pack1(t)
		raw, _ := os.ReadFile(mp)
		idx, _ := parseAtlas(string(raw))
		a, b := idx.list[0], idx.list[1]
		if a.page != b.page {
			t.Skip("first two sprites on different pages")
		}
		bad := strings.Replace(string(raw), fmt.Sprintf("    rect: [%d, %d, %d, %d]\n    trim: [%d, %d]", b.rect.Min.X, b.rect.Min.Y, b.rect.Dx(), b.rect.Dy(), b.trim.X, b.trim.Y),
			fmt.Sprintf("    rect: [%d, %d, %d, %d]\n    trim: [%d, %d]", a.rect.Min.X, a.rect.Min.Y, b.rect.Dx(), b.rect.Dy(), b.trim.X, b.trim.Y), 1)
		if err := os.WriteFile(mp, []byte(bad), 0o644); err != nil {
			t.Fatal(err)
		}
		errs := checkAtlas(root, "pawn", 128)
		if len(errs) == 0 || !strings.Contains(errs[0].Error(), "overlap") {
			t.Fatalf("errs = %v, want an overlap", errs)
		}
	})
	t.Run("missing page", func(t *testing.T) {
		root, _ := pack1(t)
		if err := os.Remove(filepath.Join(root, "generated", "atlas", "pawn_0.png")); err != nil {
			t.Fatal(err)
		}
		if errs := checkAtlas(root, "pawn", 128); len(errs) == 0 {
			t.Fatal("want an error for a missing page")
		}
	})
	t.Run("page over the limit", func(t *testing.T) {
		root, _ := pack1(t)
		if errs := checkAtlas(root, "pawn", 64); len(errs) == 0 {
			t.Fatal("want an error when pages exceed -max")
		}
	})
	t.Run("rect outside its page", func(t *testing.T) {
		root, mp := pack1(t)
		raw, _ := os.ReadFile(mp)
		idx, _ := parseAtlas(string(raw))
		r := idx.list[0].rect
		bad := strings.Replace(string(raw), fmt.Sprintf("    rect: [%d, %d, %d, %d]", r.Min.X, r.Min.Y, r.Dx(), r.Dy()),
			fmt.Sprintf("    rect: [9000, %d, %d, %d]", r.Min.Y, r.Dx(), r.Dy()), 1)
		if err := os.WriteFile(mp, []byte(bad), 0o644); err != nil {
			t.Fatal(err)
		}
		if errs := checkAtlas(root, "pawn", 128); len(errs) == 0 {
			t.Fatal("want an error for a rect outside its page")
		}
	})
}

func TestPackRejectsBadInput(t *testing.T) {
	t.Run("empty family", func(t *testing.T) {
		root := t.TempDir()
		if err := os.MkdirAll(filepath.Join(root, "metadata", "pawn"), 0o755); err != nil {
			t.Fatal(err)
		}
		if _, err := pack(root, "pawn", 64); err == nil {
			t.Fatal("want an error")
		}
	})
	t.Run("png size differs from canvas", func(t *testing.T) {
		root := t.TempDir()
		specs := sampleSpecs()[:1]
		writeFamily(t, root, "pawn", specs)
		mp := filepath.Join(root, "metadata", "pawn", specs[0].key+".yaml")
		raw, _ := os.ReadFile(mp)
		os.WriteFile(mp, []byte(strings.Replace(string(raw), "canvas: [40, 50]", "canvas: [41, 50]", 1)), 0o644)
		if _, err := pack(root, "pawn", 64); err == nil || !strings.Contains(err.Error(), "canvas") {
			t.Fatalf("err = %v", err)
		}
	})
	t.Run("coloured mask", func(t *testing.T) {
		root := t.TempDir()
		specs := []spriteSpec{{key: "a", canvas: image.Pt(8, 8), block: image.Rect(1, 1, 5, 5), tinted: true}}
		writeFamily(t, root, "pawn", specs)
		bad := image.NewNRGBA(image.Rect(0, 0, 8, 8))
		bad.SetNRGBA(2, 2, color.NRGBA{200, 10, 10, 255})
		writePNGFile(t, filepath.Join(root, "generated", "world", "pawn", "a_mask.png"), bad)
		if _, err := pack(root, "pawn", 64); err == nil {
			t.Fatal("want an error for a non-grey mask")
		}
	})
	t.Run("missing sprite file", func(t *testing.T) {
		root := t.TempDir()
		specs := sampleSpecs()[:2]
		writeFamily(t, root, "pawn", specs)
		os.Remove(filepath.Join(root, "generated", "world", "pawn", specs[1].key+".png"))
		if _, err := pack(root, "pawn", 64); err == nil {
			t.Fatal("want an error")
		}
	})
	t.Run("metadata without image", func(t *testing.T) {
		if _, err := parseSpriteMeta("r", "x", "id: x\ncanvas: [1, 1]\n"); err == nil {
			t.Fatal("want an error")
		}
		if _, err := parseSpriteMeta("r", "x", "image: a.png\ncanvas: [1]\n"); err == nil {
			t.Fatal("want an error for a bad canvas")
		}
	})
}

func TestParseAtlasRoundTrip(t *testing.T) {
	es := []*entry{{key: "a", meta: []string{"id: \"core:pawn/a\"", "canvas: [4, 5]", "tint:", "  group: skin", "  mask: m.png"},
		trim: image.Rect(1, 2, 3, 4), page: 1, x: 5, y: 6, normPath: "n"}}
	idx, err := parseAtlas(atlasYAML("pawn", 64, 2, es))
	if err != nil {
		t.Fatal(err)
	}
	if idx.family != "pawn" || idx.max != 64 || idx.pages != 2 || len(idx.list) != 1 {
		t.Fatalf("index = %+v", idx)
	}
	s := idx.list[0]
	if s.page != 1 || s.rect != image.Rect(5, 6, 7, 8) || s.trim != image.Pt(1, 2) || !s.normal || !s.mask ||
		s.canvas != image.Pt(4, 5) {
		t.Fatalf("sprite = %+v", s)
	}
	if _, err := parseAtlas("version: 1\nmax: x\n"); err == nil {
		t.Fatal("want a parse error")
	}
}

