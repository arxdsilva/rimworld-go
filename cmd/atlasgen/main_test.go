// spriteSpec is one synthetic sprite: an opaque block inside a canvas.
type spriteSpec struct {
	key    string
	canvas image.Point
	block  image.Rectangle // opaque pixels, in canvas coordinates
	tinted bool
	normal bool
	seed   uint8
}

func writePNGFile(t *testing.T, path string, img image.Image) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	f, err := os.Create(path)
	if err != nil {
		t.Fatal(err)
	}
	defer f.Close()
	if err := png.Encode(f, img); err != nil {
		t.Fatal(err)
	}
}

// writeFamily writes sprites, masks, normal maps and metadata for family
// under root, the way the Blender pipeline lays them out.
func writeFamily(t *testing.T, root, family string, specs []spriteSpec) {
	t.Helper()
	for _, s := range specs {
		img := image.NewNRGBA(image.Rectangle{Max: s.canvas})
		mask := image.NewNRGBA(image.Rectangle{Max: s.canvas})
		norm := image.NewNRGBA(image.Rectangle{Max: s.canvas})
		for y := 0; y < s.canvas.Y; y++ {
			for x := 0; x < s.canvas.X; x++ {
				mask.SetNRGBA(x, y, color.NRGBA{0, 0, 0, 255}) // opaque black outside, as Blender writes it
			}
		}
		for y := s.block.Min.Y; y < s.block.Max.Y; y++ {
			for x := s.block.Min.X; x < s.block.Max.X; x++ {
				v := s.seed + uint8(x*7+y*13)
				img.SetNRGBA(x, y, color.NRGBA{v, v ^ 0x55, 200, 255})
				mask.SetNRGBA(x, y, color.NRGBA{v | 1, v | 1, v | 1, 255})
				norm.SetNRGBA(x, y, color.NRGBA{128, v, 255, 255}) // a normal map has its sprite's alpha
			}
		}
		base := filepath.Join(root, "generated", "world", family, s.key)
		writePNGFile(t, base+".png", img)
		var meta strings.Builder
		fmt.Fprintf(&meta, "# generated by assets/source/blender/build.py - do not hand-edit\nversion: 1\nid: \"core:%s/%s\"\n", family, s.key)
		fmt.Fprintf(&meta, "image: generated/world/%s/%s.png\nscale: 2\ncanvas: [%d, %d]\nfootprint: [1, 1]\norigin_px: [16, 153]\n",
			family, s.key, s.canvas.X, s.canvas.Y)
		fmt.Fprintf(&meta, "shadow:\n  kind: blob\n  w: 0.4\n  h: 0.9\n  d: 0.4\n")
		if s.tinted {
			writePNGFile(t, base+"_mask.png", mask)
			fmt.Fprintf(&meta, "tint:\n  group: skin\n  mask: generated/world/%s/%s_mask.png\n", family, s.key)
		}
		if s.normal {
			writePNGFile(t, base+"_n.png", norm)
		}
		fmt.Fprintf(&meta, "attachments:\n  hand: [1.5, 2.5]\n")
		mp := filepath.Join(root, "metadata", family, s.key+".yaml")
		if err := os.MkdirAll(filepath.Dir(mp), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(mp, []byte(meta.String()), 0o644); err != nil {
			t.Fatal(err)
		}
	}
}

func sampleSpecs() []spriteSpec {
	var out []spriteSpec
	for i := 0; i < 23; i++ {
		w, h := 20+i%5*3, 30+i%4*4
		out = append(out, spriteSpec{
			key:    fmt.Sprintf("body_%02d", i),
			canvas: image.Pt(40, 50),
			block:  image.Rect(3+i%3, 4, 3+i%3+w/2, 4+h/2),
			tinted: i%2 == 0,
			normal: i%3 != 0,
			seed:   uint8(i * 11),
		})
	}
	return out
}

func TestNonZeroBounds(t *testing.T) {
	img := image.NewNRGBA(image.Rect(0, 0, 10, 10))
	if r := nonZero(img, 0xf); !r.Empty() {
		t.Fatalf("blank image has bounds %v", r)
	}
	img.SetNRGBA(3, 4, color.NRGBA{A: 1})
	img.SetNRGBA(7, 2, color.NRGBA{R: 9})
	if r := nonZero(img, 0xf); r != image.Rect(3, 2, 8, 5) {
		t.Fatalf("bounds = %v", r)
	}
	if r := nonZero(img, 0x1); r != image.Rect(7, 2, 8, 3) { // red only
		t.Fatalf("red bounds = %v", r)
	}
}

func TestLayoutNeverOverlapsAndStaysInPages(t *testing.T) {
	var es []*entry
	for i := 0; i < 200; i++ {
		w, h := 5+(i*7)%23, 4+(i*11)%29
		es = append(es, &entry{key: fmt.Sprintf("k%03d", i), trim: image.Rect(0, 0, w, h)})
	}
	const maxPx = 96
	sizes, err := layout(es, maxPx)
	if err != nil {
		t.Fatal(err)
	}
	if len(sizes) < 2 {
		t.Fatalf("expected several pages, got %d", len(sizes))
	}
	for _, sz := range sizes {
		if sz[0] > maxPx || sz[1] > maxPx {
			t.Fatalf("page %v exceeds %d", sz, maxPx)
		}
	}
	rects := make([]image.Rectangle, len(es))
	for i, e := range es {
		r := image.Rect(e.x, e.y, e.x+e.trim.Dx(), e.y+e.trim.Dy())
		if !r.In(image.Rect(0, 0, sizes[e.page][0], sizes[e.page][1])) {
			t.Fatalf("%s: %v outside its page %v", e.key, r, sizes[e.page])
		}
		rects[i] = r
	}
	for i := range es {
		for j := i + 1; j < len(es); j++ {
			if es[i].page == es[j].page && rects[i].Overlaps(rects[j]) {
				t.Fatalf("%s %v and %s %v overlap on page %d", es[i].key, rects[i], es[j].key, rects[j], es[i].page)
			}
		}
	}
}

