SIZE_LENGTH = {"XS": 0.44, "S": 0.6, "M": 0.95, "L": 1.4, "XL": 2.0}


def body_length(size):
    """Tiles of body length for a size class like "S+" or "L-"."""
    base = size.rstrip("+-")
    k = 1.15 if size.endswith("+") else 0.85 if size.endswith("-") else 1.0
    return SIZE_LENGTH[base] * k


