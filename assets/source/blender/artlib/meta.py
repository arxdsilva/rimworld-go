"""Sidecar metadata writer (ART spec §24). Emits a small, stable YAML subset."""
import os

from . import contracts


def _fmt(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, float):
        return ("%.4f" % v).rstrip("0").rstrip(".") if v != int(v) else "%.1f" % v
    if isinstance(v, (list, tuple)):
        return "[" + ", ".join(_fmt(x) for x in v) + "]"
    if isinstance(v, str):
        return '"%s"' % v if any(c in v for c in ":#{}[],") else v
    return str(v)


def _emit(lines, d, indent):
    for k, v in d.items():
        if isinstance(v, dict):
            lines.append("%s%s:" % ("  " * indent, k))
            _emit(lines, v, indent + 1)
        else:
            lines.append("%s%s: %s" % ("  " * indent, k, _fmt(v)))


def write(family, name, data):
    d = {"version": contracts.METADATA_VERSION,
         "id": "%s:%s/%s" % (contracts.NAMESPACE, family, name)}
    d.update(data)
    if family in ("terrain", "weather", "overlay"):
        d.setdefault("shadow", {"kind": "none", "w": 0.0, "h": 0.0, "d": 0.0})
    lines = ["# generated by assets/source/blender/build.py - do not hand-edit"]
    _emit(lines, d, 0)
    path = os.path.join(contracts.METADATA_DIR, family, name + ".yaml")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    return path
